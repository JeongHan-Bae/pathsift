import { mkdtemp, mkdir, readFile, readdir, rename, rm, stat, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { x as extractTar } from 'tar';

const root = fileURLToPath(new URL('..', import.meta.url));
const preview = path.join(root, 'release-preview');
const marker = '.pathsift-generated';
const markerText = 'Generated by npm run stage:release. Do not edit.\n';
const npmCli = process.env.npm_execpath;
if (!npmCli) throw new Error('Run through npm run stage:release');

async function packedFiles(directory, prefix = '') {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await packedFiles(path.join(directory, entry.name), relative));
    else files.push(relative);
  }
  return files;
}

const staging = await mkdtemp(path.join(root, '.pathsift-preview-'));
try {
  const result = spawnSync(process.execPath, [npmCli, 'pack', '--json', '--ignore-scripts', '--pack-destination', staging], {
    cwd: root, encoding: 'utf8'
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`npm pack failed:\n${result.stdout}\n${result.stderr}`);
  const [packed] = JSON.parse(result.stdout);
  if (!packed?.filename || !Array.isArray(packed.files)) throw new Error('npm pack returned invalid metadata');
  const tarball = path.join(staging, packed.filename);
  const packageTree = path.join(staging, 'package');
  await mkdir(packageTree);
  await extractTar({ file: tarball, cwd: packageTree, strip: 1, strict: true });
  const expected = packed.files.map(file => file.path).sort();
  const actual = (await packedFiles(packageTree)).sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(`Extracted package differs from npm pack metadata.\nExpected: ${expected.join(', ')}\nActual: ${actual.join(', ')}`);
  }
  await writeFile(path.join(staging, 'pack-metadata.json'), JSON.stringify(packed, null, 2) + '\n');
  await writeFile(path.join(staging, marker), markerText);
  let previewExists = false;
  try { await stat(preview); previewExists = true; }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previewExists) {
    const recognized = (await stat(preview)).isDirectory() &&
      await readFile(path.join(preview, marker), 'utf8').catch(() => null) === markerText;
    if (!recognized) throw new Error(`Refusing to replace unrecognized directory: ${preview}`);
    await rm(preview, { recursive: true });
  }
  await rename(staging, preview);
  console.log(`Release preview: ${preview}`);
  console.log(`Packed archive: ${path.join(preview, packed.filename)}`);
  console.log(`Extracted package: ${path.join(preview, 'package')} (${actual.length} files)`);
} catch (error) {
  await rm(staging, { recursive: true, force: true });
  throw error;
}
